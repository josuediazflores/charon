#!/usr/bin/env python3
"""Regenerate Resources/Backdrop.png and Resources/AppIcon.icns.

Both pieces of artwork in this app are computed, not drawn. There is no source
image anywhere in the repo and none is needed: everything below is a formula
plus a seeded RNG, so re-running this file reproduces the shipped bytes
exactly. That is the whole provenance -- if you want different art, edit the
numbers here rather than dropping a picture into Resources/.

    python3 scripts/generate-art.py          # both
    python3 scripts/generate-art.py backdrop # just the backdrop
    python3 scripts/generate-art.py icon     # just the icns

Needs Pillow, NumPy, and (for the icns) macOS `iconutil`.
"""
import os
import shutil
import subprocess
import sys
import tempfile

import numpy as np
from PIL import Image, ImageDraw
from PIL.PngImagePlugin import PngInfo

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(os.path.dirname(HERE), "Resources")

BACKDROP_W, BACKDROP_H = 4344, 3258
SEED = 20260826

PROVENANCE = (
    "Generated by scripts/generate-art.py (procedural: radial light field + "
    "seeded value noise, thresholded through an 8x8 Bayer matrix). No source "
    "image; re-running the script reproduces this file."
)


def bayer(n: int) -> np.ndarray:
    """Ordered-dither threshold matrix, built by the recursive doubling rule."""
    m = np.array([[0]], dtype=np.float64)
    while m.shape[0] < n:
        m = np.block([[4 * m, 4 * m + 2], [4 * m + 3, 4 * m + 1]])
    return m


def tiled_threshold(order: int, w: int, h: int) -> np.ndarray:
    thr = (bayer(order) + 0.5) / float(order * order)
    reps_y = h // order + 1
    reps_x = w // order + 1
    return np.tile(thr, (reps_y, reps_x))[:h, :w].astype(np.float32)


# --------------------------------------------------------------------------
# Backdrop: the picture behind the window.
# --------------------------------------------------------------------------

def smooth_noise(w: int, h: int, cells: int, rng) -> np.ndarray:
    """Low-resolution white noise, bicubically upsampled into smooth blobs."""
    ch = max(2, int(round(cells * h / w)))
    small = rng.random((ch, cells)).astype(np.float32)
    img = Image.fromarray((small * 255).astype(np.uint8), mode="L")
    img = img.resize((w, h), Image.BICUBIC)
    return np.asarray(img, dtype=np.float32) / 255.0


def backdrop():
    W, H = BACKDROP_W, BACKDROP_H
    rng = np.random.default_rng(SEED)

    ys = np.linspace(0.0, 1.0, H, dtype=np.float32)[:, None]
    xs = np.linspace(0.0, 1.0, W, dtype=np.float32)[None, :]
    aspect = W / H

    # Primary light, set above centre so the bright mass sits in the upper
    # third and the window's own black ground carries the bottom of the frame.
    dx = (xs - 0.52) * aspect
    dy = ys - 0.36
    r = np.sqrt(dx * dx + dy * dy)
    field = np.exp(-(r / 0.17) ** 2) + np.exp(-(r / 0.44) ** 1.5) * 0.50

    # A second, weaker pole low-left, so the composition is not one dot.
    dx2 = (xs - 0.16) * aspect
    dy2 = ys - 0.86
    r2 = np.sqrt(dx2 * dx2 + dy2 * dy2)
    field += np.exp(-(r2 / 0.30) ** 1.7) * 0.16

    field += (1.0 - ys) * 0.05  # vertical wash, darkest at the bottom edge

    # Three octaves of soft noise, applied multiplicatively so the grain lives
    # in the lit region and the shadows stay clean.
    n = (
        smooth_noise(W, H, 10, rng) * 0.55
        + smooth_noise(W, H, 34, rng) * 0.30
        + smooth_noise(W, H, 96, rng) * 0.15
    )
    field = field * (1.0 + (n - 0.5) * 0.55)

    field = np.clip(field, 0.0, 1.0) ** 2.1
    field = field * 0.97 + 0.004

    bits = field > tiled_threshold(8, W, H)
    out = Image.fromarray((bits * 255).astype(np.uint8), mode="L").convert("1")

    meta = PngInfo()
    meta.add_text("Comment", PROVENANCE)
    path = os.path.join(RES, "Backdrop.png")
    out.save(path, optimize=True, pnginfo=meta)
    print("wrote", path, out.size, "1-bit")


# --------------------------------------------------------------------------
# AppIcon: a dithered orb on black.
# --------------------------------------------------------------------------

# macOS icon grid: the art plate is 824/1024 of the canvas with a 185.4/1024
# corner radius, which leaves the standard breathing room in the Dock.
PLATE = 824.0 / 1024.0
CORNER = 185.4 / 1024.0
SUPERSAMPLE = 4  # for the plate's alpha edge only -- the art itself is 1-bit


def orb_field(S: int) -> np.ndarray:
    """Continuous-tone shading of a lit sphere plus its halo, in [0,1]."""
    c = (S - 1) / 2.0
    yy, xx = np.mgrid[0:S, 0:S].astype(np.float64)
    x = (xx - c) / S
    y = (yy - c) / S
    r = np.sqrt(x * x + y * y)

    R = 0.265  # sphere radius, canvas-relative
    inside = r <= R
    nx = np.where(inside, x / R, 0.0)
    ny = np.where(inside, y / R, 0.0)
    nz = np.sqrt(np.clip(1.0 - nx * nx - ny * ny, 0.0, 1.0))

    L = np.array([-0.45, -0.55, 0.70])
    L = L / np.linalg.norm(L)
    diff = np.clip(nx * L[0] + ny * L[1] + nz * L[2], 0.0, 1.0)

    body = 0.12 + 0.88 * diff ** 1.15 + 0.55 * diff ** 26  # lambert + specular
    body = np.where(inside, body, 0.0)

    # The halo is a large-canvas luxury: at 32pt and below an ordered dither of
    # it is a scatter of loose pixels, so below 64 it is simply dropped.
    amp = 0.34 if S >= 64 else 0.0
    halo = np.exp(-(np.clip(r - R, 0.0, None) / 0.085) ** 1.5) * amp
    halo = np.where(inside, 0.0, halo)

    return np.clip(body + halo, 0.0, 1.0)


def plate_alpha(S: int) -> np.ndarray:
    """Antialiased rounded-square mask, supersampled then boxed back down."""
    big = S * SUPERSAMPLE
    m = Image.new("L", (big, big), 0)
    inset = (1.0 - PLATE) / 2.0 * big
    ImageDraw.Draw(m).rounded_rectangle(
        [inset, inset, big - inset - 1, big - inset - 1],
        radius=CORNER * big,
        fill=255,
    )
    return np.asarray(m.resize((S, S), Image.BOX), dtype=np.uint8)


def render_icon(S: int) -> Image.Image:
    # Each variant is shaded and dithered at its own native size: downsampling
    # a 1-bit image turns its lattice into mush. The matrix order drops with
    # the canvas so the sphere still reads when there are sixteen pixels to
    # say it in.
    order = 8 if S >= 256 else (4 if S >= 64 else 2)
    bits = orb_field(S) > tiled_threshold(order, S, S)
    lum = (bits * 255).astype(np.uint8)

    rgba = np.zeros((S, S, 4), dtype=np.uint8)
    rgba[..., 0] = rgba[..., 1] = rgba[..., 2] = lum
    rgba[..., 3] = plate_alpha(S)
    return Image.fromarray(rgba, mode="RGBA")


def icon():
    variants = [
        ("icon_16x16.png", 16),
        ("icon_16x16@2x.png", 32),
        ("icon_32x32.png", 32),
        ("icon_32x32@2x.png", 64),
        ("icon_128x128.png", 128),
        ("icon_128x128@2x.png", 256),
        ("icon_256x256.png", 256),
        ("icon_256x256@2x.png", 512),
        ("icon_512x512.png", 512),
        ("icon_512x512@2x.png", 1024),
    ]
    tmp = tempfile.mkdtemp(prefix="charon-icon-")
    work = os.path.join(tmp, "AppIcon.iconset")
    os.makedirs(work)
    try:
        cache = {}
        for name, size in variants:
            if size not in cache:
                cache[size] = render_icon(size)
            cache[size].save(os.path.join(work, name))
        path = os.path.join(RES, "AppIcon.icns")
        subprocess.run(["iconutil", "-c", "icns", work, "-o", path], check=True)
        print("wrote", path, os.path.getsize(path), "bytes")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else "all"
    if which in ("all", "backdrop"):
        backdrop()
    if which in ("all", "icon"):
        icon()
    if which not in ("all", "backdrop", "icon"):
        sys.exit("usage: generate-art.py [backdrop|icon]")


if __name__ == "__main__":
    main()
